#!/usr/bin/env python3
"""
Pre-Commit Hook Installer for AutoBugHunter 24/7.
Installs cross-platform git pre-commit hook into .git/hooks/pre-commit
pointing to scripts/pre_commit_secret_sanitizer.py.
"""

from __future__ import annotations

import argparse
import os
import pathlib
import stat
import subprocess
import sys
from typing import Optional


def find_git_dir(start_path: Optional[pathlib.Path] = None) -> Optional[pathlib.Path]:
    """Locate the git directory, handling regular repos, worktrees, and submodules."""
    if start_path is None:
        start_path = pathlib.Path(__file__).resolve().parent.parent

    # Try git CLI first
    try:
        res = subprocess.run(
            ["git", "rev-parse", "--git-dir"],
            cwd=start_path,
            capture_output=True,
            text=True,
            check=True,
        )
        git_dir_raw = res.stdout.strip()
        if git_dir_raw:
            p = pathlib.Path(git_dir_raw)
            return p if p.is_absolute() else (start_path / p).resolve()
    except Exception:
        pass

    # Filesystem traversal fallback
    curr = start_path.resolve()
    for parent in [curr] + list(curr.parents):
        dot_git = parent / ".git"
        if dot_git.is_dir():
            return dot_git
        elif dot_git.is_file():
            # Submodule or worktree pointing to actual gitdir
            try:
                content = dot_git.read_text(encoding="utf-8").strip()
                if content.startswith("gitdir:"):
                    target = content.split(":", 1)[1].strip()
                    p = pathlib.Path(target)
                    return p if p.is_absolute() else (parent / p).resolve()
            except Exception:
                pass

    return None


def get_hooks_dir(git_dir: pathlib.Path, repo_root: pathlib.Path) -> pathlib.Path:
    """Get the hooks directory, querying git rev-parse --git-path hooks if possible."""
    try:
        res = subprocess.run(
            ["git", "rev-parse", "--git-path", "hooks"],
            cwd=repo_root,
            capture_output=True,
            text=True,
            check=True,
        )
        hooks_raw = res.stdout.strip()
        if hooks_raw:
            p = pathlib.Path(hooks_raw)
            return p if p.is_absolute() else (repo_root / p).resolve()
    except Exception:
        pass
    return git_dir / "hooks"


def generate_hook_script(python_path: str = sys.executable) -> str:
    """Generate shell wrapper invoking Python reliably across Windows and POSIX."""
    py_posix = pathlib.Path(python_path).as_posix()
    return f"""#!/bin/sh
# AutoBugHunter 24/7 Git Pre-Commit Secret Sanitizer Hook
# Auto-generated by scripts/install_hooks.py

INSTALL_PYTHON="{py_posix}"

# 1. Try python interpreter that installed this hook
if [ -f "$INSTALL_PYTHON" ] || [ -x "$INSTALL_PYTHON" ]; then
    exec "$INSTALL_PYTHON" scripts/pre_commit_secret_sanitizer.py "$@"
fi

# 2. Fallback to python3 in PATH
if command -v python3 >/dev/null 2>&1; then
    exec python3 scripts/pre_commit_secret_sanitizer.py "$@"
fi

# 3. Fallback to python in PATH
if command -v python >/dev/null 2>&1; then
    exec python scripts/pre_commit_secret_sanitizer.py "$@"
fi

echo "ERROR: AutoBugHunter pre-commit hook requires Python to run scripts/pre_commit_secret_sanitizer.py." >&2
echo "Please ensure python or python3 is available in your PATH." >&2
exit 1
"""


def install_pre_commit_hook(
    repo_root: Optional[pathlib.Path] = None,
    python_path: Optional[str] = None,
    force: bool = False,
) -> bool:
    """Install pre-commit hook into .git/hooks/pre-commit with executable permissions."""
    if repo_root is None:
        repo_root = pathlib.Path(__file__).resolve().parent.parent

    if python_path is None:
        python_path = sys.executable

    git_dir = find_git_dir(repo_root)
    if not git_dir:
        sys.stderr.write(
            f"[ERROR] Could not find .git directory in or above '{repo_root}'.\n"
            "       Please initialize Git first with 'git init'.\n"
        )
        return False

    hooks_dir = get_hooks_dir(git_dir, repo_root)
    try:
        hooks_dir.mkdir(parents=True, exist_ok=True)
    except OSError as e:
        sys.stderr.write(f"[ERROR] Failed to create hooks directory '{hooks_dir}': {e}\n")
        return False

    hook_file = hooks_dir / "pre-commit"

    if hook_file.exists() and not force:
        try:
            existing_content = hook_file.read_text(encoding="utf-8")
            if "scripts/pre_commit_secret_sanitizer.py" in existing_content:
                # Already installed AutoBugHunter hook; refresh content
                pass
            else:
                backup_file = hooks_dir / f"pre-commit.backup.{os.getpid()}"
                hook_file.rename(backup_file)
                print(f"[!] Existing pre-commit hook backed up to: {backup_file}")
        except Exception as e:
            sys.stderr.write(f"[WARN] Failed checking existing hook: {e}\n")

    wrapper_content = generate_hook_script(python_path)
    try:
        hook_file.write_bytes(wrapper_content.encode("utf-8"))
    except OSError as e:
        sys.stderr.write(f"[ERROR] Failed writing hook to '{hook_file}': {e}\n")
        return False

    # Set executable permissions (0o755) on POSIX
    if hasattr(os, "chmod") and os.name != "nt":
        try:
            target_mode = stat.S_IRWXU | stat.S_IRGRP | stat.S_IXGRP | stat.S_IROTH | stat.S_IXOTH
            os.chmod(hook_file, target_mode)
        except OSError as e:
            sys.stderr.write(f"[WARN] Could not set executable mode on '{hook_file}': {e}\n")

    try:
        if sys.stdout.encoding and sys.stdout.encoding.lower() not in ("utf-8", "utf8"):
            sys.stdout.reconfigure(encoding="utf-8", errors="replace")
    except Exception:
        pass

    print(f"[OK] Pre-commit hook installed successfully at: {hook_file}")
    return True


def check_hook_installed(repo_root: Optional[pathlib.Path] = None) -> bool:
    """Verify whether the hook is currently installed."""
    if repo_root is None:
        repo_root = pathlib.Path(__file__).resolve().parent.parent

    git_dir = find_git_dir(repo_root)
    if not git_dir:
        return False

    hook_file = get_hooks_dir(git_dir, repo_root) / "pre-commit"
    if not hook_file.exists():
        return False

    try:
        content = hook_file.read_text(encoding="utf-8")
        return "scripts/pre_commit_secret_sanitizer.py" in content
    except Exception:
        return False


def main() -> int:
    parser = argparse.ArgumentParser(description="Install AutoBugHunter pre-commit hook.")
    parser.add_argument(
        "--repo-dir",
        "-d",
        type=pathlib.Path,
        default=None,
        help="Repository root directory (default: parent of scripts/)",
    )
    parser.add_argument(
        "--python-path",
        "-p",
        type=str,
        default=sys.executable,
        help="Custom Python executable path for the hook wrapper",
    )
    parser.add_argument(
        "--force",
        "-f",
        action="store_true",
        help="Overwrite existing pre-commit hook without backup",
    )
    parser.add_argument(
        "--check",
        action="store_true",
        help="Check if pre-commit hook is already installed",
    )

    args = parser.parse_args()

    if args.check:
        installed = check_hook_installed(args.repo_dir)
        if installed:
            print("[OK] Pre-commit secret sanitizer hook is installed.")
            return 0
        else:
            print("[FAIL] Pre-commit secret sanitizer hook is NOT installed.")
            return 1

    success = install_pre_commit_hook(
        repo_root=args.repo_dir,
        python_path=args.python_path,
        force=args.force,
    )
    return 0 if success else 1


if __name__ == "__main__":
    sys.exit(main())
